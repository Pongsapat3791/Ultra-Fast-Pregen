package io.github.pongsapat3791.ufplink;

import io.github.pongsapat3791.ufplink.api.LinkMachine;
import io.github.pongsapat3791.ufplink.api.LinkPlan;
import io.github.pongsapat3791.ufplink.api.LinkRun;
import io.github.pongsapat3791.ufplink.api.LinkTile;
import io.github.pongsapat3791.ultrafastpregen.api.PregenWorlds;
import java.io.IOException;
import java.nio.ByteBuffer;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.HashMap;
import java.util.HashSet;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;
import java.util.concurrent.atomic.AtomicLong;
import java.util.concurrent.atomic.AtomicReference;

/**
 * A distributed pregen on the host: the area is cut into square tiles of tile_chunks chunks, and
 * each tile is generated by one client. A tile is handed out only while none of the eight tiles
 * around it is being generated, together with every chunk the host already has in and around it
 * (as far as the engine reads neighbors), so the client joins its tile to them as one server
 * would. What comes back is merged: chunks the host lacks are written, chunks it sent are
 * replaced only if still exactly as sent, and chunks the server holds are left alone. A plan can
 * say which machine takes which tile (see assign).
 */
final class HostJob {
    private static final AtomicReference<HostJob> CURRENT = new AtomicReference<>();
    /** The last job, also after it ended, for the API. */
    private static volatile HostJob latest;
    private static final AtomicLong UNITS = new AtomicLong();

    enum TileState { PENDING, ASSIGNED, DONE }

    static final class Tile {
        final int tileX;
        final int tileZ;
        final int minChunkX;
        final int minChunkZ;
        volatile TileState state = TileState.PENDING;
        volatile HostSession owner;
        volatile long unit;
        /** The machine the plan gives it to; null for any machine. */
        final String planned;
        /** The machine that has it, or last had it. */
        volatile String worker;

        Tile(int tileX, int tileZ, int minChunkX, int minChunkZ, String planned) {
            this.tileX = tileX;
            this.tileZ = tileZ;
            this.minChunkX = minChunkX;
            this.minChunkZ = minChunkZ;
            this.planned = planned;
        }
    }

    /**
     * A chunk the host has in or around a tile: sent to the client with the hash it is compared by
     * later; {@code full}: it is fully generated.
     */
    record Context(ChunkPos pos, ByteBuffer frame, byte[] hash, boolean full) {}

    /** A chunk a client sends back, and the hash of the version the host sent it (null when it sent none). */
    record Replacement(ChunkPos pos, ByteBuffer data, byte[] baseHash) {}

    final String dimension;
    final int tileChunks;
    private final int worldK;
    private final int centerX;
    private final int centerZ;
    private final List<Tile> tiles = new ArrayList<>();
    private final long startedAt = System.nanoTime();
    private final boolean helpOthers;
    private volatile long endedAt;
    private volatile String stopReason;
    private volatile long written;
    private volatile long replaced;
    private volatile long kept;
    private volatile long held;
    private volatile long rejected;
    private volatile long skipped;

    private HostJob(String dimension, int worldK, int centerX, int centerZ, int tileChunks,
                    Map<Long, String> plan, boolean helpOthers) {
        this.dimension = dimension;
        this.worldK = worldK;
        this.centerX = centerX;
        this.centerZ = centerZ;
        this.tileChunks = tileChunks;
        this.helpOthers = helpOthers;
        for (int[] tile : cut(worldK, centerX, centerZ, tileChunks)) {
            tiles.add(new Tile(tile[0], tile[1], tile[0] * tileChunks, tile[1] * tileChunks, plan.get(key(tile[0], tile[1]))));
        }
    }

    /** The tiles of an area, as {tileX, tileZ}: nearest to the center first, so the area grows outwards like a run on one server. */
    private static List<int[]> cut(int worldK, int centerX, int centerZ, int tileChunks) {
        int half = worldK * 500;
        int minChunkX = Math.floorDiv(centerX - half, 16);
        int minChunkZ = Math.floorDiv(centerZ - half, 16);
        int maxChunkX = Math.floorDiv(centerX - half + worldK * 1000 - 1, 16);
        int maxChunkZ = Math.floorDiv(centerZ - half + worldK * 1000 - 1, 16);
        List<int[]> tiles = new ArrayList<>();
        for (int tz = Math.floorDiv(minChunkZ, tileChunks); tz <= Math.floorDiv(maxChunkZ, tileChunks); tz++) {
            for (int tx = Math.floorDiv(minChunkX, tileChunks); tx <= Math.floorDiv(maxChunkX, tileChunks); tx++) {
                tiles.add(new int[] {tx, tz});
            }
        }
        int centerChunkX = Math.floorDiv(centerX, 16);
        int centerChunkZ = Math.floorDiv(centerZ, 16);
        tiles.sort(Comparator.comparingLong(tile -> {
            long dx = tile[0] * tileChunks + tileChunks / 2 - centerChunkX;
            long dz = tile[1] * tileChunks + tileChunks / 2 - centerChunkZ;
            return dx * dx + dz * dz;
        }));
        return tiles;
    }

    static long key(int tileX, int tileZ) {
        return ((long) tileX << 32) | (tileZ & 0xFFFFFFFFL);
    }

    /** An area's tiles shared among the machines (see LinkPlanner). */
    static LinkPlan plan(String dimension, int centerX, int centerZ, int worldK, int tileChunks, List<LinkMachine> machines) {
        List<int[]> tiles = cut(worldK, centerX, centerZ, tileChunks);
        Map<Long, String> shares = LinkPlanner.share(tiles, machines);
        List<LinkTile> planned = new ArrayList<>();
        for (int[] tile : tiles) {
            planned.add(new LinkTile(tile[0], tile[1], tile[0] * tileChunks, tile[1] * tileChunks, shares.get(key(tile[0], tile[1])),
                    LinkTile.State.PENDING, null));
        }
        return new LinkPlan(dimension, centerX, centerZ, worldK, tileChunks, planned);
    }

    static HostJob current() {
        return CURRENT.get();
    }

    static java.util.Optional<HostJob> latest() {
        return java.util.Optional.ofNullable(latest);
    }

    /** Starts handing out the area's tiles to any machine; an error or null. */
    static String start(String dimension, int worldK, int x, int z, int tileChunks) {
        return start(dimension, worldK, x, z, tileChunks, Map.of(), true);
    }

    /** Starts a plan: the area's tiles go to the machines it names; an error or null. */
    static String start(String dimension, LinkPlan plan, boolean helpOthers) {
        Map<Long, String> machines = new HashMap<>();
        for (LinkTile tile : plan.tiles()) {
            if (tile.planned() != null) machines.put(key(tile.tileX(), tile.tileZ()), tile.planned());
        }
        return start(dimension, plan.sizeK(), plan.centerX(), plan.centerZ(), plan.tileChunks(), machines, helpOthers);
    }

    private static String start(String dimension, int worldK, int x, int z, int tileChunks,
                                Map<Long, String> plan, boolean helpOthers) {
        if (!PregenJob.fitsWorld(worldK, x, z)) return String.format(Locale.ROOT, "A %dk area around [%d, %d] reaches past the world limit.", worldK, x, z);
        if (PregenJob.current() != null || ImportTask.current() != null) return "A pregen or import is running on this server.";
        HostJob job = new HostJob(dimension, worldK, x, z, tileChunks, plan, helpOthers);
        if (!CURRENT.compareAndSet(null, job)) return "A distributed pregen is running: /ufplink host status, /ufplink cancel.";
        latest = job;
        UfpLink.LOGGER.info("[UFP Link] Distributed pregen of {}: {}k x {}k around [{}, {}] in {} tiles of {} x {} chunks{}.",
                dimension, worldK, worldK, x, z, job.tiles.size(), tileChunks, tileChunks,
                plan.isEmpty() ? "" : ", planned for " + new java.util.TreeSet<>(plan.values()));
        return null;
    }

    /** Whether every tile is done. */
    private synchronized boolean finished() {
        return tiles.stream().allMatch(tile -> tile.state == TileState.DONE);
    }

    void cancel(String reason) {
        if (stopReason == null) stopReason = reason;
    }

    boolean stopped() {
        return stopReason != null;
    }

    /**
     * A tile for the client, or null when none can be handed out now. Marks it assigned. Tiles planned
     * for this machine or for nobody come first. With helpOthers it then takes tiles of a machine that
     * is not connected and, once none of its own is left, of any machine.
     */
    synchronized Tile assign(HostSession session) {
        if (stopReason != null) return null;
        String name = session.name();
        boolean ownLeft = false;
        Tile other = null;
        for (Tile tile : tiles) {
            if (tile.state != TileState.PENDING) continue;
            boolean own = tile.planned == null || tile.planned.equals(name);
            ownLeft |= own;
            if (neighborBusy(tile)) continue;
            if (own) return give(tile, session);
            if (other == null && helpOthers && !connected(tile.planned)) other = tile;
        }
        if (other == null && helpOthers && !ownLeft) {
            for (Tile tile : tiles) {
                if (tile.state == TileState.PENDING && !neighborBusy(tile)) return give(tile, session);
            }
        }
        return other != null ? give(other, session) : null;
    }

    private Tile give(Tile tile, HostSession session) {
        tile.state = TileState.ASSIGNED;
        tile.owner = session;
        tile.worker = session.name();
        tile.unit = UNITS.incrementAndGet();
        return tile;
    }

    private static boolean connected(String machine) {
        LinkHost host = LinkHost.running();
        return host != null && host.sessions().stream().anyMatch(session -> machine.equals(session.name()));
    }

    private boolean neighborBusy(Tile tile) {
        for (Tile other : tiles) {
            if (other != tile && other.state == TileState.ASSIGNED
                    && Math.abs(other.tileX - tile.tileX) <= 1 && Math.abs(other.tileZ - tile.tileZ) <= 1) {
                return true;
            }
        }
        return false;
    }

    /** A client's tiles go back to the queue (it disconnected or failed). */
    synchronized void release(HostSession session) {
        for (Tile tile : tiles) {
            if (tile.state == TileState.ASSIGNED && tile.owner == session) {
                tile.state = TileState.PENDING;
                tile.owner = null;
                tile.worker = null;
            }
        }
    }

    synchronized void release(Tile tile) {
        if (tile.state == TileState.ASSIGNED) {
            tile.state = TileState.PENDING;
            tile.owner = null;
            tile.worker = null;
        }
    }

    /** Why no tile was handed out (all done, or waiting for neighbors). */
    synchronized String idleReason() {
        if (stopReason != null) return "the distributed pregen was stopped (" + stopReason + ")";
        long pending = tiles.stream().filter(tile -> tile.state == TileState.PENDING).count();
        return pending == 0 ? "every tile is handed out or done" : pending + " tiles wait for tiles next to them or for their machine";
    }

    /** The job as the API shows it. */
    synchronized LinkRun snapshot() {
        List<LinkTile> shown = new ArrayList<>();
        for (Tile tile : tiles) {
            LinkTile.State state = switch (tile.state) {
                case PENDING -> LinkTile.State.PENDING;
                case ASSIGNED -> LinkTile.State.ASSIGNED;
                case DONE -> LinkTile.State.DONE;
            };
            shown.add(new LinkTile(tile.tileX, tile.tileZ, tile.minChunkX, tile.minChunkZ, tile.planned, state, tile.worker));
        }
        boolean running = CURRENT.get() == this;
        long ended = running || endedAt == 0 ? System.nanoTime() : endedAt;
        LinkPlan plan = new LinkPlan(dimension, centerX, centerZ, worldK, tileChunks, shown);
        return new LinkRun(plan, helpOthers, running, written, replaced, kept, held, rejected, skipped, (ended - startedAt) / 1_000_000L,
                stopReason, running ? idleReason() : null);
    }

    /**
     * The chunks the host has in the tile and as far around it as the engine reads (core and halo),
     * as frames with their hashes. Read through the IO worker, so saves the server queued count.
     */
    List<Context> context(Tile tile) throws IOException {
        PregenWorlds worlds = UfpLink.worlds();
        int halo = worlds.neighborChunks();
        int side = tileChunks + 2 * halo;
        long[] chunks = new long[side * side];
        for (int x = 0; x < side; x++) {
            for (int z = 0; z < side; z++) chunks[x * side + z] = ChunkPos.asLong(tile.minChunkX - halo + x, tile.minChunkZ - halo + z);
        }
        List<Context> context = new ArrayList<>();
        for (PregenWorlds.StoredChunk chunk : worlds.readChunks(dimension, chunks)) {
            context.add(new Context(new ChunkPos(chunk.chunk()), chunk.frame(), chunk.hash(), chunk.fullyGenerated()));
        }
        return context;
    }

    /** Whether the host already has every chunk of the tile fully generated (then no client needs to make it). */
    boolean alreadyGenerated(Tile tile, List<Context> context) {
        int full = 0;
        for (Context chunk : context) {
            int x = chunk.pos().x - tile.minChunkX;
            int z = chunk.pos().z - tile.minChunkZ;
            if (chunk.full() && x >= 0 && z >= 0 && x < tileChunks && z < tileChunks) full++;
        }
        return full == tileChunks * tileChunks;
    }

    /** Marks a tile the host already has done, without a client. */
    void skip(Tile tile) {
        skipped++;
        markDone(tile);
    }

    private void markDone(Tile tile) {
        synchronized (this) {
            tile.state = TileState.DONE;
            tile.owner = null;
        }
        if (finished()) {
            UfpLink.LOGGER.info("[UFP Link] Distributed pregen of {} done: {}", dimension, describe());
            endedAt = System.nanoTime();
            CURRENT.compareAndSet(this, null);
        }
    }

    /** A client's chunks for its tile, merged into the target (see the class comment). Marks the tile done. */
    void merge(Tile tile, List<Replacement> results) throws IOException {
        PregenWorlds worlds = UfpLink.worlds();
        int dataVersion = worlds.dataVersion();
        List<Replacement> valid = new ArrayList<>();
        for (Replacement result : results) {
            String problem;
            try {
                problem = ChunkFrames.checkChunk(result.data(), result.pos(), dataVersion);
            } catch (IOException | RuntimeException failure) {
                problem = failure.toString();
            }
            if (problem == null) {
                valid.add(result);
            } else {
                rejected++;
                UfpLink.LOGGER.warn("[UFP Link] Chunk [{}, {}] from a client not merged: {}", result.pos().x, result.pos().z, problem);
            }
        }
        long[] positions = valid.stream().mapToLong(result -> result.pos().toLong()).toArray();
        Set<Long> heldNow = new HashSet<>();
        for (long chunk : worlds.heldChunks(dimension, positions)) heldNow.add(chunk);
        held += heldNow.size();
        List<PregenWorlds.ChunkWrite> writes = new ArrayList<>();
        for (Replacement result : valid) {
            if (heldNow.contains(result.pos().toLong())) continue;
            writes.add(new PregenWorlds.ChunkWrite(result.pos().toLong(), result.data(), true, result.baseHash()));
        }
        PregenWorlds.WriteResult result = worlds.writeChunks(dimension, PregenWorlds.Store.CHUNKS, writes,
                PregenWorlds.WriteRule.ABSENT_OR_UNCHANGED, false);
        written += result.written().length - result.replaced();
        replaced += result.replaced();
        kept += result.kept();
        markDone(tile);
    }

    /** Ends the job when nothing is assigned any more after a stop. */
    synchronized void endIfStopped() {
        if (stopReason != null && tiles.stream().noneMatch(tile -> tile.state == TileState.ASSIGNED)) {
            if (endedAt == 0) endedAt = System.nanoTime();
            CURRENT.compareAndSet(this, null);
        }
    }

    synchronized String describe() {
        long done = tiles.stream().filter(tile -> tile.state == TileState.DONE).count();
        long busy = tiles.stream().filter(tile -> tile.state == TileState.ASSIGNED).count();
        long seconds = (System.nanoTime() - startedAt) / 1_000_000_000L;
        return String.format(Locale.ROOT, "%dk x %dk around [%d, %d] in %s: %d/%d tiles done%s, %d being generated | %,d chunks written,"
                        + " %,d edge chunks joined, %,d kept, %,d held by the server, %,d rejected | %dm %02ds%s",
                worldK, worldK, centerX, centerZ, dimension, done, tiles.size(),
                skipped > 0 ? String.format(Locale.ROOT, " (%d already generated here)", skipped) : "", busy, written, replaced, kept,
                held, rejected, seconds / 60, seconds % 60, stopReason != null ? " | stopping: " + stopReason : "");
    }
}
