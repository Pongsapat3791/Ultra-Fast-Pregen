package io.github.pongsapat3791.ufplink;

import io.github.pongsapat3791.ufplink.api.LinkClientStatus;
import io.github.pongsapat3791.ufplink.region.RegionReader;
import io.github.pongsapat3791.ufplink.tool.RegionWriter;
import io.github.pongsapat3791.ultrafastpregen.api.PregenRequest;
import io.github.pongsapat3791.ultrafastpregen.api.PregenStatus;
import io.github.pongsapat3791.ultrafastpregen.api.PregenWorlds;
import io.github.pongsapat3791.ultrafastpregen.api.StartResult;
import java.io.DataInputStream;
import java.io.DataOutputStream;
import java.io.IOException;
import java.net.InetSocketAddress;
import java.net.Socket;
import java.nio.ByteBuffer;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.stream.Stream;

/**
 * A client of a distributed pregen: connects to the host (and again whenever the connection
 * drops), proves it has the secret and that its world generates like the host's (fingerprint),
 * then asks for tiles. Each tile is generated by Ultra Fast Pregen in a fresh separate world that first
 * gets the host's chunks in and around the tile; then every chunk that is new or changed goes back.
 */
final class LinkClient {
    private static volatile LinkClient running;

    private record Context(ByteBuffer frame, byte[] hash) {}

    private final NetworkConfig config;
    private volatile boolean stopped;
    private volatile Socket socket;
    /** Whether a run of this client is going on. */
    private volatile boolean generating;
    private volatile String state = "starting";
    private volatile long tilesDone;
    private volatile long chunksSent;
    /** Why it is not connected; null while it is, or before the first try ended. */
    private volatile String problem;
    private volatile boolean connected;
    /** The address that answered; all of them until one has. */
    private volatile String address;

    private LinkClient(NetworkConfig config) {
        this.config = config;
        this.address = config.host;
    }

    static LinkClient running() {
        return running;
    }

    static void start(NetworkConfig config) {
        LinkClient client = new LinkClient(config);
        running = client;
        Thread thread = new Thread(client::run, "UFP-Link-Client");
        thread.setDaemon(true);
        thread.start();
    }

    static void stop() {
        LinkClient client = running;
        running = null;
        if (client == null) return;
        client.stopped = true;
        if (client.generating) UfpLink.pregen().stop();
        Socket open = client.socket;
        if (open != null) {
            try {
                open.close();
            } catch (IOException ignored) {
                // closing anyway
            }
        }
    }

    String describe() {
        return String.format(Locale.ROOT, "Client %s of %s, port %d: %s | %d tiles, %,d chunks sent", config.name, address, config.port,
                state, tilesDone, chunksSent);
    }

    LinkClientStatus status() {
        return new LinkClientStatus(config.name, address, config.port, state, tilesDone, chunksSent);
    }

    boolean connected() {
        return connected;
    }

    String problem() {
        return problem;
    }

    /** What went wrong, in words that say what to do. */
    private String explain(Exception failure, boolean reached) {
        String where = config.host.replace(",", ", ") + ", port " + config.port;
        if (failure instanceof java.io.EOFException) return "the host closed the connection";
        if (failure instanceof java.net.ConnectException) return "nothing answers at " + where + ": is the host running, and is this its address?";
        if (failure instanceof java.net.SocketTimeoutException) return "no answer from " + where + ": allow that port through the host's firewall";
        if (failure instanceof java.net.UnknownHostException) return "there is no machine named " + config.host;
        if (reached && failure instanceof java.net.SocketException) return "the connection to the host was lost";
        return failure.getMessage() != null ? failure.getMessage() : failure.toString();
    }

    /** The first of the host's addresses that answers; with several, each gets a short try. */
    private Socket connect() throws IOException {
        String[] addresses = config.host.split(",");
        IOException last = null;
        for (String candidate : addresses) {
            Socket connection = new Socket();
            socket = connection;
            try {
                connection.connect(new InetSocketAddress(candidate.trim(), config.port), addresses.length > 1 ? 3_000 : 10_000);
                address = candidate.trim();
                return connection;
            } catch (IOException failure) {
                connection.close();
                last = failure;
            }
        }
        throw last;
    }

    private void run() {
        String lastProblem = null;
        while (!stopped && UfpLink.worlds().serverRunning()) {
            boolean reached = false;
            state = "connecting";
            try (Socket connection = connect()) {
                reached = true;
                connection.setTcpNoDelay(true);
                DataInputStream in = Messages.input(connection.getInputStream());
                DataOutputStream out = Messages.output(connection.getOutputStream());
                handshake(in, out);
                lastProblem = null;
                problem = null;
                connected = true;
                work(in, out);
            } catch (IOException | RuntimeException failure) {
                connected = false;
                if (stopped) return;
                String why = explain(failure, reached);
                if (!why.equals(lastProblem)) UfpLink.LOGGER.warn("[UFP Link] Client: {}; trying again every 10 s", why);
                lastProblem = why;
                problem = why;
                state = "waiting for the host (" + why + ")";
                sleep(10_000);
            }
        }
    }

    private void handshake(DataInputStream in, DataOutputStream out) throws IOException {
        Messages.Message challenge = Messages.read(in);
        if (challenge.type() != Messages.CHALLENGE) throw new IOException("the host did not start the handshake");
        int protocol = challenge.body().readInt();
        if (protocol != Messages.PROTOCOL) throw new IOException("the host speaks protocol " + protocol + ", this client " + Messages.PROTOCOL);
        byte[] hostNonce = new byte[32];
        challenge.body().readFully(hostNonce);
        byte[] ownNonce = Messages.nonce();
        Messages.Writer auth = new Messages.Writer(Messages.AUTH);
        auth.out.write(Messages.proof(config.secret, "client", hostNonce));
        auth.out.write(ownNonce);
        auth.send(out);
        Messages.Message ok = Messages.read(in);
        if (ok.type() != Messages.AUTH_OK) throw new IOException("the host refused the secret");
        byte[] proof = new byte[32];
        ok.body().readFully(proof);
        if (!Messages.sameProof(proof, Messages.proof(config.secret, "host", ownNonce))) {
            throw new IOException("the host does not know the secret");
        }
        Messages.Writer hello = new Messages.Writer(Messages.HELLO);
        hello.out.writeInt(Messages.PROTOCOL);
        hello.out.writeUTF(config.name);
        hello.out.writeUTF(UfpLink.version());
        hello.out.writeInt(Runtime.getRuntime().availableProcessors());
        hello.out.writeLong(Runtime.getRuntime().maxMemory());
        hello.out.writeUTF(System.getProperty("os.name", "?") + " " + System.getProperty("os.arch", ""));
        Messages.writeBytes(hello.out, Fingerprint.compute().toJsonString().getBytes(StandardCharsets.UTF_8));
        hello.send(out);
        Messages.Message answer = Messages.read(in);
        if (answer.type() == Messages.REJECT) throw new IOException("the host refused this client: " + answer.body().readUTF());
        if (answer.type() != Messages.ACCEPT) throw new IOException("unexpected answer " + answer.type());
        UfpLink.LOGGER.info("[UFP Link] Client {}: connected to the host {}:{}", config.name, address, config.port);
        state = "connected";
    }

    private void work(DataInputStream in, DataOutputStream out) throws IOException {
        while (!stopped) {
            new Messages.Writer(Messages.REQUEST).send(out);
            Messages.Message message = Messages.read(in);
            if (message.type() == Messages.IDLE) {
                int retry = message.body().readInt();
                state = "idle: " + message.body().readUTF();
                sleep(retry * 1000L);
                continue;
            }
            if (message.type() != Messages.TILE) throw new IOException("unexpected message " + message.type());
            DataInputStream body = message.body();
            long unit = body.readLong();
            String dimension = body.readUTF();
            int minChunkX = body.readInt();
            int minChunkZ = body.readInt();
            int chunks = body.readInt();
            int contextCount = body.readInt();
            Map<ChunkPos, Context> context = new HashMap<>();
            for (int i = 0; i < contextCount; i++) {
                Messages.Message part = Messages.read(in);
                if (part.type() != Messages.CONTEXT) throw new IOException("expected the tile's context");
                ChunkPos pos = new ChunkPos(part.body().readInt(), part.body().readInt());
                byte[] hash = new byte[32];
                part.body().readFully(hash);
                context.put(pos, new Context(ByteBuffer.wrap(Messages.readBytes(part.body())), hash));
            }
            generate(unit, dimension, minChunkX, minChunkZ, chunks, context, in, out);
        }
    }

    private void generate(long unit, String dimension, int minChunkX, int minChunkZ, int chunks, Map<ChunkPos, Context> context,
                          DataInputStream in, DataOutputStream out) throws IOException {
        String tile = "tile at chunk [" + minChunkX + ", " + minChunkZ + "]";
        PregenWorlds worlds = UfpLink.worlds();
        if (!worlds.dimensions().contains(dimension)) {
            fail(out, unit, "this client has no " + dimension);
            return;
        }
        String wanted = SeparateWorld.idFor(dimension);
        Path folder = worlds.separateWorldFolder(dimension, wanted);
        state = "generating " + tile + " (" + context.size() + " chunks of the host around it)";
        String separate = null;
        String result;
        try {
            SeparateWorld.delete(folder);
            writeContext(folder, context);
            separate = worlds.openSeparateWorld(dimension, wanted);
            result = run(separate, minChunkX, minChunkZ, chunks);
        } finally {
            generating = false;
            if (separate != null) {
                try {
                    worlds.closeSeparateWorld(separate);
                } catch (IOException | RuntimeException failure) {
                    UfpLink.LOGGER.warn("[UFP Link] Closing the separate world failed", failure);
                }
            }
        }
        if (result != null) {
            fail(out, unit, "the run stopped: " + result);
            SeparateWorld.delete(folder);
            return;
        }
        state = "sending " + tile;
        int halo = worlds.neighborChunks();
        int sent = 0;
        for (Path file : regionFiles(folder.resolve("region"))) {
            try (RegionReader reader = RegionReader.open(file)) {
                for (int[] chunk : reader.chunks()) {
                    ChunkPos pos = new ChunkPos(chunk[0], chunk[1]);
                    // A separate world can hold more than was asked for: Bukkit makes a new world's spawn first.
                    if (pos.x < minChunkX - halo || pos.x >= minChunkX + chunks + halo
                            || pos.z < minChunkZ - halo || pos.z >= minChunkZ + chunks + halo) continue;
                    ByteBuffer frame = reader.frame(pos.x, pos.z);
                    Context sentBefore = context.get(pos);
                    if (sentBefore != null && sentBefore.frame().equals(frame)) continue;
                    Messages.Writer message = new Messages.Writer(Messages.RESULT);
                    message.out.writeLong(unit);
                    message.out.writeInt(pos.x);
                    message.out.writeInt(pos.z);
                    message.out.writeBoolean(sentBefore != null);
                    if (sentBefore != null) message.out.write(sentBefore.hash());
                    byte[] data = new byte[frame.remaining()];
                    frame.get(data);
                    Messages.writeBytes(message.out, data);
                    message.send(out);
                    sent++;
                }
            }
        }
        Messages.Writer done = new Messages.Writer(Messages.DONE);
        done.out.writeLong(unit);
        done.send(out);
        state = "waiting for the host to merge " + tile;
        Messages.Message merged = Messages.read(in);
        if (merged.type() != Messages.MERGED) throw new IOException("expected MERGED");
        tilesDone++;
        chunksSent += sent;
        UfpLink.LOGGER.info("[UFP Link] Client {}: {} done, {} chunks sent ({} of the host's were unchanged).", config.name, tile, sent,
                context.size());
        SeparateWorld.delete(folder);
        state = "connected";
    }

    /** The host's chunks in and around the tile, into the separate world before it is generated. */
    private static void writeContext(Path folder, Map<ChunkPos, Context> context) throws IOException {
        Map<Long, List<ChunkPos>> byRegion = new LinkedHashMap<>();
        for (ChunkPos pos : context.keySet()) {
            byRegion.computeIfAbsent(ChunkPos.asLong(pos.getRegionX(), pos.getRegionZ()), key -> new ArrayList<>()).add(pos);
        }
        for (Map.Entry<Long, List<ChunkPos>> region : byRegion.entrySet()) {
            String name = "r." + ChunkPos.getX(region.getKey()) + "." + ChunkPos.getZ(region.getKey()) + ".mca";
            try (RegionWriter writer = RegionWriter.open(folder.resolve("region").resolve(name))) {
                for (ChunkPos pos : region.getValue()) writer.write(pos.x, pos.z, context.get(pos).frame());
                writer.commit();
            }
        }
    }

    /** Generates the tile in the separate world, in one batch when the heap allows. Null when it completed, or what stopped it. */
    private String run(String separate, int minChunkX, int minChunkZ, int chunks) {
        int size = chunks * 16;
        int x = minChunkX * 16 + size / 2;
        int z = minChunkZ * 16 + size / 2;
        var pregen = UfpLink.pregen();
        StartResult started = pregen.start(PregenRequest.square(separate, x, z, size / 2).withBatchSize(size).keepingExistingChunks());
        if (!started.started()) return started.message();
        generating = true;
        while (pregen.isRunning()) sleep(500);
        PregenStatus status = pregen.status().orElse(null);
        return status != null && status.state() == PregenStatus.State.COMPLETED ? null : status != null ? status.stage() : "no status";
    }

    private static void fail(DataOutputStream out, long unit, String why) throws IOException {
        UfpLink.LOGGER.warn("[UFP Link] Client: {}", why);
        Messages.Writer failed = new Messages.Writer(Messages.FAILED);
        failed.out.writeLong(unit);
        failed.out.writeUTF(why);
        failed.send(out);
    }

    private static List<Path> regionFiles(Path folder) throws IOException {
        if (!Files.isDirectory(folder)) return List.of();
        try (Stream<Path> files = Files.list(folder)) {
            return files.filter(file -> RegionReader.regionOf(file) != null).sorted().toList();
        }
    }

    private static void sleep(long millis) {
        try {
            Thread.sleep(millis);
        } catch (InterruptedException interrupted) {
            Thread.currentThread().interrupt();
        }
    }
}
