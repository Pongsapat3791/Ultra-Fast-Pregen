import com.example.pregen.mixin.ChunkMapAccessor;
import it.unimi.dsi.fastutil.longs.LongSet;
import it.unimi.dsi.fastutil.longs.LongSets;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.concurrent.CompletableFuture;
import java.util.concurrent.ExecutionException;
import java.util.concurrent.TimeUnit;
import java.util.concurrent.TimeoutException;
import net.minecraft.core.SectionPos;
import net.minecraft.network.protocol.game.ClientboundLevelChunkWithLightPacket;
import net.minecraft.server.MinecraftServer;
import net.minecraft.server.level.ChunkHolder;
import net.minecraft.server.level.ServerChunkCache;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.world.level.ChunkPos;
import net.minecraft.world.level.chunk.ChunkAccess;
import net.minecraft.world.level.chunk.status.ChunkStatus;
import net.minecraft.world.level.chunk.ImposterProtoChunk;
import net.minecraft.world.level.chunk.LevelChunk;
import net.minecraft.world.level.chunk.ProtoChunk;
import net.minecraft.world.level.levelgen.structure.BoundingBox;
import net.minecraft.world.ticks.LevelChunkTicks;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.material.Fluid;

/**
 * Replace server-held terrain on the server thread, so later saves retain regeneration.
 *
 * Called from the generation thread. The work is split into short server-thread tasks, and the
 * server thread never waits on anything here: a server-thread task that loads a chunk blocks the
 * whole tick until that chunk is generated, which can wait on the IO thread for a long time
 * (a 60-second watchdog crash was observed when post-processing reached an unloaded neighbor).
 */
final class LoadedChunkRegeneration {
    /** Chunks replaced per server-thread task, to keep each tick short. */
    private static final int SLICE = 16;
    private static final long TIMEOUT_SECONDS = 120;

    private LoadedChunkRegeneration() {}

    static void apply(ServerLevel level, InMemoryChunkGrid grid) {
        apply(level, grid, LongSets.EMPTY_SET, false);
    }

    /**
     * Chunks in {@code keep} already existed and are left as the server holds them. With
     * {@code keepFull}, so is any chunk the server holds fully generated by the time it would be
     * replaced (a player may have just loaded it); only part-way generated ones are replaced.
     */
    static void apply(ServerLevel level, InMemoryChunkGrid grid, LongSet keep, boolean keepFull) {
        MinecraftServer server = level.getServer();
        long[] positions = Arrays.stream(grid.getCorePositions()).filter(pos -> !keep.contains(pos)).toArray();

        // Let save chains the server already started for these chunks finish first.
        CompletableFuture<Void> saves = await(server.submit(() -> {
            ChunkMapAccessor map = (ChunkMapAccessor) level.getChunkSource().chunkMap;
            List<CompletableFuture<?>> pending = new ArrayList<>();
            for (long pos : positions) {
                ChunkHolder holder = holder(map, pos);
                if (holder != null) pending.add(holder.getSaveSyncFuture());
            }
            return CompletableFuture.allOf(pending.toArray(new CompletableFuture[0]));
        }), "server chunk list");
        await(saves, "pending chunk saves");

        for (int start = 0; start < positions.length; start += SLICE) {
            // When stopping, submit() would run the task on this thread instead of the server's.
            if (!server.isRunning()) return;
            int from = start;
            int to = Math.min(positions.length, start + SLICE);
            await(server.submit(() -> {
                ChunkMapAccessor map = (ChunkMapAccessor) level.getChunkSource().chunkMap;
                for (int index = from; index < to; index++) {
                    long pos = positions[index];
                    ChunkHolder holder = holder(map, pos);
                    ChunkAccess held = holder == null ? null : holder.getLatestChunk();
                    if (keepFull && WorldChunkIO.isFull(held)) continue;
                    if (held instanceof ImposterProtoChunk imposter) held = imposter.getWrapped();
                    if (held == null) continue;
                    ProtoChunk generated = grid.getChunk(ChunkPos.getX(pos), ChunkPos.getZ(pos));
                    replace(level, held, generated);
                }
                return null;
            }), "loaded chunk replacement");
        }
    }

    private static <T> T await(CompletableFuture<T> future, String what) {
        try {
            return future.get(TIMEOUT_SECONDS, TimeUnit.SECONDS);
        } catch (TimeoutException timeout) {
            throw new IllegalStateException("Timed out waiting for " + what + " (is the server thread busy?)", timeout);
        } catch (InterruptedException interrupted) {
            Thread.currentThread().interrupt();
            throw new IllegalStateException("Interrupted while waiting for " + what, interrupted);
        } catch (ExecutionException failure) {
            throw new IllegalStateException(what + " failed", failure.getCause());
        }
    }

    private static ChunkHolder holder(ChunkMapAccessor map, long pos) {
        ChunkHolder holder = map.pregen$getUpdatingChunk(pos);
        if (holder == null) holder = map.pregen$getVisibleChunk(pos);
        return holder != null ? holder : map.pregen$getPendingUnloads().get(pos);
    }

    /**
     * Post-processing ticks fluids and updates block shapes, reading blocks one past the chunk
     * edge. Run it only when all eight neighbors are already loaded, so it can never load or
     * generate a chunk on the server thread. Otherwise the positions stay in the chunk, are
     * saved with it, and vanilla processes them when the chunk next becomes ticking.
     */
    private static boolean neighborsLoaded(ServerLevel level, ChunkPos pos) {
        ServerChunkCache chunks = level.getChunkSource();
        for (int dz = -1; dz <= 1; dz++) {
            for (int dx = -1; dx <= 1; dx++) {
                if ((dx != 0 || dz != 0) && chunks.getChunkNow(pos.x + dx, pos.z + dz) == null) return false;
            }
        }
        return true;
    }

    private static void replace(ServerLevel level, ChunkAccess held, ProtoChunk generated) {
        LevelChunk live = held instanceof LevelChunk chunk ? chunk : null;
        for (var pos : List.copyOf(held.getBlockEntitiesPos())) held.removeBlockEntity(pos);
        if (live != null) {
            live.clearAllBlockEntities();
        }
        System.arraycopy(generated.getSections(), 0, held.getSections(), 0, held.getSections().length);
        for (var entry : generated.getHeightmaps()) {
            if (live == null || ChunkStatus.FULL.heightmapsAfter().contains(entry.getKey())) {
                held.setHeightmap(entry.getKey(), entry.getValue().getRawData());
            }
        }
        held.setAllStarts(generated.getAllStarts());
        held.setAllReferences(generated.getAllReferences());
        held.setBlendingData(null);
        held.setInhabitedTime(0);
        System.arraycopy(generated.getPostProcessing(), 0, held.getPostProcessing(), 0, held.getPostProcessing().length);
        held.initializeLightSources();
        held.setLightCorrect(generated.isLightCorrect());
        if (live != null) {
            LevelChunk fresh = new LevelChunk(level, generated, null);
            fresh.unpackTicks(level.getGameTime());
            live.unpackTicks(level.getGameTime());
            ChunkPos pos = live.getPos();
            BoundingBox bounds = new BoundingBox(pos.getMinBlockX(), level.getMinBuildHeight(), pos.getMinBlockZ(),
                    pos.getMaxBlockX(), level.getMaxBuildHeight() - 1, pos.getMaxBlockZ());
            level.getBlockTicks().clearArea(bounds);
            level.getFluidTicks().clearArea(bounds);
            fresh.getBlockEntities().values().forEach(live::setBlockEntity);
            generated.getBlockEntityNbts().values().forEach(live::setBlockEntityNbt);
            ((LevelChunkTicks<Block>) fresh.getBlockTicks()).getAll().forEach(live.getBlockTicks()::schedule);
            ((LevelChunkTicks<Fluid>) fresh.getFluidTicks()).getAll().forEach(live.getFluidTicks()::schedule);
            live.registerAllBlockEntitiesAfterLevelLoad();
            for (int section = 0; section < live.getSections().length; section++) {
                level.getPoiManager().checkConsistencyWithBlocks(
                        SectionPos.of(pos, live.getSectionYFromSectionIndex(section)), live.getSections()[section]);
            }
            if (neighborsLoaded(level, pos)) live.postProcessGeneration();
            ClientboundLevelChunkWithLightPacket packet = new ClientboundLevelChunkWithLightPacket(
                    live, level.getChunkSource().getLightEngine(), null, null);
            level.getChunkSource().chunkMap.getPlayers(pos, false).forEach(player -> player.connection.send(packet));
        } else {
            generated.getBlockEntities().values().forEach(held::setBlockEntity);
            generated.getBlockEntityNbts().values().forEach(held::setBlockEntityNbt);
            ((ProtoChunk) held).setLightEngine(level.getChunkSource().getLightEngine());
            // The server may still have generation steps queued for this chunk; they must not
            // redo terrain or features on it now (see ChunkStepMixin). Light steps still run.
            ((RegeneratedChunk) held).pregen$markRegenerated();
            ((ProtoChunk) held).setPersistedStatus(ChunkStatus.FULL);
        }
        held.setUnsaved(true);
    }
}
