package com.example.pregen;

import it.unimi.dsi.fastutil.longs.LongCollection;
import java.nio.file.Path;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.concurrent.CompletableFuture;
import net.minecraft.nbt.CompoundTag;

/**
 * A dimension's chunk storage as a run reads and writes it: Minecraft's own (WorldChunkIO, on Spigot
 * and CraftBukkit) or the one of Paper's chunk system (MoonriseChunkIO).
 */
interface ChunkStorage {
    /** Whether chunks are handed over framed as a region file stores them (else as NBT, see EncodedChunk). */
    boolean framesChunks();

    /** The dimension's folder (its region folder's parent). */
    Path dimensionFolder();

    /**
     * Which chunks of the given regions exist, fully generated and in any status (see
     * WorldChunkIO.StoredChunks); a missing region file is not created.
     */
    CompletableFuture<WorldChunkIO.StoredChunks> findStoredInRegions(LongCollection regionKeys);

    /** A stored chunk's data, including a save the server has queued. */
    CompletableFuture<Optional<CompoundTag>> load(long chunk);

    /**
     * Stores the chunks; with {@code overwrite} false, a chunk stored fully generated by the time it
     * is written (a player's) is kept.
     */
    WorldChunkIO.PendingWrite write(List<WorldChunkIO.EncodedChunk> chunks, boolean overwrite);

    /**
     * Applies feature writes from a later batch to chunks this run already saved (see
     * SeamWrites.applyToSaved); completes with the number of chunks changed.
     */
    CompletableFuture<Integer> mergeIntoSaved(Map<Long, List<SeamWrites.Write>> writes);
}
