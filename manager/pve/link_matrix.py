#!/usr/bin/env python3
"""Ultra Fast Pregen, Link and the Manager together on every server, through the page's API and the console.

Run it through ufp-run, from ~/compat: [EXTRA_JARS="more mods"] link_matrix.py <folder of jars> [target ...]. For each
target a host and a client of the same server (Folia, which cannot create a world, hosts a Paper client):
  page      the page shows both Ultra Fast Pregen and Link, and the client is among the machines
  plan      a plan of 1,000 x 1,000 blocks: every tile generated by the client and complete on the host's disk
  alone     the host's own pregen in a separate world, in each of the three dimensions (not Folia): every chunk merged,
            the separate world deleted
  resume    a pregen stopped half way and continued, then one cut short by a server stop and continued after the restart:
            the same separate world opens again (not Folia)
  same      a region of the plan generated by the client in its own world, drawn by both pages: the separate world's
            terrain is the terrain of the world
  import    /ufplink check and import of the stopped client's world on the host: its area, with a pig made for this
  merge     the merge tool from the stopped host into the stopped client, then the client started: all of it is there
  errors    nothing in the logs of the host and the client
One line per target in results/link-matrix.txt; the logs stay in logs/mgr-lm-<target>-h.log and -c.log."""
