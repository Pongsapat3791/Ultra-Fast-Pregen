#!/usr/bin/env python3
"""Link and the Manager with no config file written by hand, the way someone new uses them.

Run from the compat folder: link_easy.py <folder of jars> [target ...]. For each target two servers with nothing set up (Folia
hosts a Paper client, as it cannot create a world), and a third of another seed:
  login     /ufpmanager gives a code; the page trades it for the token once; a wrong code and the same code again are refused
  invite    /ufplink invite makes a host at once, and says what a client needs; the page shows it as a host, with its port
  join      /ufplink join on the other server connects at once and says so; it is among the machines
  plan      every tile of a plan generated by that client, complete on the host's disk
  restart   both servers stopped and started: still host and client, connected again, with no file touched
  leave     /ufplink leave on the client, then from the host's page: no role on either, no machine left
  page      the same set-up from the pages: a host and its invite, a client joined with it, a wrong invite and a server's own invite refused
  address   an invite whose first address answers nothing: the client takes the next
  seed      a server of another seed joins: whoever joined hears why not, and the host lists it under Refused
  port      a second host on this machine takes the next free port
  errors    nothing in the logs
One line per target in results/link-easy.txt; the logs stay in logs/mgr-ez-<target>-h.log, -c.log and -d.log."""
import json
import os
import re
import sys
import time
import urllib.error
import urllib.parse
import urllib.request

import link_matrix as lm

HOST, CLIENT, OTHER = "ez-h", "ez-c", "ez-d"
OTHER_WEB = 25584
EXPECTED = ("refused this client", " refused: ", "Connection refused", "nothing answers at", "closed the connection", "connection to the host was lost", "Port 25599 is in use")


def start(instance, target, port, web, seed="42"):
    return lm.script(instance, "start", target, lm.ufp_jar(target), lm.JARS + "/ufplink-0.3.0.jar", lm.JARS + "/ufpmanager-0.2.0.jar", PORT=str(port),
                     WEB=str(web), SEED=seed, JVM=os.environ.get("LINK_JVM", "-Xms1G -Xmx3G")).splitlines()[-1:]


def said(instance, command, pattern, seconds=30):
    """Runs a console command and returns the first match of the pattern in what the log gets after it."""
    seen = len(lm.log_text(instance))
    lm.console(instance, command)
    end = time.time() + seconds
    while time.time() < end:
        found = re.search(pattern, lm.log_text(instance)[seen:])
        if found:
            return found
        time.sleep(0.5)
    return None


def login(code, web):
    data = urllib.parse.urlencode({"code": code}).encode()
    request = urllib.request.Request("http://127.0.0.1:%d/api/login" % web, data)
    try:
        with urllib.request.urlopen(request, timeout=20) as response:
            return json.load(response).get("token")
    except urllib.error.HTTPError:
        return None


def poll(web=lm.HOST_WEB):
    return lm.api("/api/poll", web)["link"]


def machines():
    return [m["name"] for m in poll()["machines"]]


def check_login(result):
    code = said(HOST, "ufpmanager", r"#code=(\w+)")
    if not code:
        result["login_message"] = "no code in the log"
        return False
    result["login"] = [bool(login("WRONG123", lm.HOST_WEB)), login(code.group(1), lm.HOST_WEB) == lm.TOKEN, bool(login(code.group(1), lm.HOST_WEB))]
    return result["login"] == [False, True, False]


def check_invite(result):
    found = said(HOST, "ufplink invite", r"/ufplink join (ufp1-[\w-]+)")
    if not found:
        return False
    result["code"] = found.group(1)
    result["needs"] = bool(lm.wait_for(lambda: "seed 42" in lm.log_text(HOST), 30))
    link = poll()
    result["role_port"] = [link["role"], link["port"]]
    return result["needs"] and link["role"] == "host" and link["port"] > 0


def check_join(result):
    answer = said(CLIENT, "ufplink join " + result["code"], r"Connected\.|Not connected: [^\n]*", 40)
    result["joined"] = answer.group(0)[:160] if answer else None
    return bool(answer) and answer.group(0) == "Connected." and lm.wait_for(lambda: len(machines()) == 1, 20) \
        and poll(lm.CLIENT_WEB)["role"] == "client"


def check_plan(result):
    """Tiles of the default size here, more than the area: all done, and the area on the host's disk."""
    place = {"dimension": lm.OVERWORLD, "x": 4000, "z": 4000, "sizeK": 1}
    plan = lm.api("/api/link/plan", **place)
    answer = lm.api("/api/link/start", **place, name=plan["names"], assign=";".join("%d,%d,%d" % (t[0], t[1], t[2]) for t in plan["tiles"]), helpOthers="true")
    if not answer["started"]:
        result["plan_message"] = answer["message"]
    finished = lm.wait_for(lambda: not lm.api("/api/poll")["link"]["run"]["running"], 420)
    run = lm.api("/api/poll")["link"]["run"]
    done = [t for t in run["tiles"] if t[3] == 2]
    chunks = sum(lm.region_chunks(x, z) for x in (6, 7, 8) for z in (6, 7, 8))
    result["plan"] = "%d/%d tiles, %d written, %d on disk" % (len(done), len(run["tiles"]), run["written"], chunks)
    return finished and len(done) == len(run["tiles"]) and chunks >= 4096


def check_restart(result):
    lm.script(CLIENT, "stop", KEEP="1")
    lm.script(HOST, "stop", KEEP="1")
    result["restart_host"] = lm.script(HOST, "again").splitlines()[-1:]
    result["restart_client"] = lm.script(CLIENT, "again").splitlines()[-1:]
    lm.wait_for(lambda: lm.api("/api/info") is not None, 30)
    return lm.wait_for(lambda: len(machines()) == 1, 60) and poll()["role"] == "host" and poll(lm.CLIENT_WEB)["role"] == "client"


def check_leave(result):
    left = said(CLIENT, "ufplink leave", r"has left the network")
    gone = lm.wait_for(lambda: len(machines()) == 0, 30)
    answer = lm.api("/api/link/leave", go="1")
    result["leave"] = [bool(left), gone, answer, poll()["role"], poll(lm.CLIENT_WEB)["role"]]
    return bool(left) and gone and answer["started"] and poll()["role"] == "none" and poll(lm.CLIENT_WEB)["role"] == "none"


def check_page(result):
    invite = lm.api("/api/link/invite", address="127.0.0.1")["invite"]
    result["invite_line"] = invite[:24]
    own = lm.api("/api/link/join", invite=invite)
    wrong = lm.api("/api/link/join", lm.CLIENT_WEB, invite="ufp1-nonsense")
    joined = lm.api("/api/link/join", lm.CLIENT_WEB, invite=invite)
    result["page_answers"] = [own, wrong, joined]
    connected = lm.wait_for(lambda: len(machines()) == 1, 40)
    return connected and own["started"] is False and "own invite" in own["message"] and wrong["started"] is False and joined["started"] is True


def check_addresses(result):
    lm.api("/api/link/leave", lm.CLIENT_WEB, go="1")
    lm.wait_for(lambda: len(machines()) == 0, 30)
    invite = lm.api("/api/link/invite", address="192.0.2.1,127.0.0.1")["invite"]
    answer = said(CLIENT, invite[1:], r"Connected\.|Not connected: [^\n]*", 40)
    result["address_answer"] = answer.group(0)[:160] if answer else None
    client = poll(lm.CLIENT_WEB)["client"]
    result["address_used"] = client["host"] if client else None
    return bool(answer) and answer.group(0) == "Connected." and client["host"] == "127.0.0.1"


def check_seed(result):
    found = said(HOST, "ufplink invite 127.0.0.1", r"/ufplink join (ufp1-[\w-]+)")
    result["other"] = start(OTHER, result["other_target"], 25574, OTHER_WEB, "43")
    before = len(poll()["refusals"])
    answer = said(OTHER, "ufplink join " + found.group(1), r"Not connected: [^\n]*|Connected\.", 40)
    result["seed_answer"] = answer.group(0)[:200] if answer else None
    refused = lm.wait_for(lambda: len(poll()["refusals"]) > before, 30)
    result["seed_refused"] = str(poll()["refusals"][:1])[:240]
    return bool(answer) and "eed" in answer.group(0) and refused


def check_port(result):
    said(OTHER, "ufplink leave", r"has left the network")
    second = said(OTHER, "ufplink invite 127.0.0.1", r"This server is a host, at [\d., ]+, port (\d+)")
    result["second_port"] = second.group(1) if second else None
    return bool(second) and int(second.group(1)) != poll()["port"]


def play(target):
    result = {"ok": {}}
    folia = target.startswith("folia")
    client = "paper-26.2" if folia else target
    result["other_target"] = client
    print("[%s] %s" % (time.strftime("%H:%M:%S"), target), flush=True)
    result["host"] = start(HOST, target, 25572, lm.HOST_WEB)
    result["client"] = start(CLIENT, client, 25573, lm.CLIENT_WEB)
    for name, check in (("login", check_login), ("invite", check_invite), ("join", check_join), ("plan", check_plan), ("restart", check_restart),
                        ("leave", check_leave), ("page", check_page), ("address", check_addresses), ("seed", check_seed), ("port", check_port)):
        lm.step(result, name, check)
    time.sleep(2)
    lines = lm.log_errors(HOST) + lm.log_errors(CLIENT) + lm.log_errors(OTHER)
    warnings = [line for instance in (HOST, CLIENT, OTHER) for line in lm.log_text(instance).splitlines()
                if lm.LINK_WARNINGS.search(line) and not any(word in line for word in EXPECTED + lm.EXPECTED_WARNINGS)]
    result["errors"] = len(lines)
    result["warnings"] = len(warnings)
    if lines:
        result["first_error"] = lines[0].strip()[:220]
    if warnings:
        result["first_warning"] = warnings[0].strip()[:220]
    return result


def stop_all(target):
    for instance, name in ((HOST, "h"), (CLIENT, "c"), (OTHER, "d")):
        if lm.log_files(instance):
            with open("logs/mgr-ez-%s-%s.log" % (target, name), "w", errors="replace") as out:
                out.write(lm.log_text(instance))
        lm.script(instance, "stop")


def main():
    stop_all("none")
    with open("results/link-easy.txt", "a", buffering=1) as out:
        for target in sys.argv[2:]:
            began = time.time()
            try:
                result = play(target)
            except Exception as failure:
                result = {"ok": {"played": False}, "failed": repr(failure)[:300]}
            stop_all(target)
            passed = all(result["ok"].values()) and not result.get("errors") and not result.get("warnings")
            line = "%s %-18s %3d s %s" % ("PASS" if passed else "FAIL", target, time.time() - began, json.dumps(result))
            print(line, flush=True)
            out.write(line + "\n")
    print("LINK_EASY_DONE", flush=True)


if __name__ == "__main__":
    main()
